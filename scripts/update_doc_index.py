#!/usr/bin/env python3
"""
Wire the markdown documentation into the Doxygen page tree.

Doxygen picks up every ``*.md`` file under ``src/`` and ``doc/`` on its own, but
without help it renders them as one flat alphabetical list of "Related Pages"
under machine-generated URLs such as
``md_src_fem_kernel_doc__r_e_a_d_m_e.html``.  This script supplies the two
things Doxygen needs to build a real navigation tree:

  1. a stable ``{#anchor}`` on the first heading of every page, which fixes the
     generated URL (``fem_kernel_index.html``) and gives ``@ref`` a target;

  2. ``doc/doxygen_nav.dox``, a generated file holding the whole page
     hierarchy as ``@subpage`` directives, including a generated "Example
     decks" page that collects the per-deck READMEs under ``examples/``.

The hierarchy deliberately lives in the ``.dox`` file rather than in the
markdown.  The module READMEs already curate a "Documentation Files" section for
readers browsing the repository on the web, and Doxygen directives written into
those files would show up there as literal ``@subpage`` text.  Keeping the tree
in a ``.dox`` file leaves the markdown clean on both surfaces.

The script is idempotent; re-run it after adding, renaming or removing a
document.

    python3 scripts/update_doc_index.py [--check]

``--check`` reports what would change and exits non-zero instead of writing,
which is what a CI job or a pre-commit hook should call.
"""

import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAV = os.path.join(REPO, "doc", "doxygen_nav.dox")
GROUPS = os.path.join(REPO, "doc", "groups.dox")

BEGIN = "<!-- BEGIN doxygen page tree (generated by scripts/update_doc_index.py) -->"
END = "<!-- END doxygen page tree -->"

# doc/mainpage.md is the Doxygen landing page; it is the one markdown file that
# is allowed to carry @subpage directives, because it exists only for Doxygen.
MAINPAGE = os.path.join(REPO, "doc", "mainpage.md")


